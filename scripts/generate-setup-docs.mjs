import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createSetupGuide, renderClientMarkdown, renderSetupMarkdown } from '../packages/setup-guide/index.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const guide = createSetupGuide({ lang: 'en' });
const notice = '<!-- Generated by npm run docs:generate from packages/setup-guide. Do not edit directly. -->\n\n';
const files = new Map([
  ['docs/setup/README.md', notice + renderSetupMarkdown({ lang: 'en' })],
  ['docs/setup/de.md', notice + renderSetupMarkdown({ lang: 'de' })],
  ['skills/backlane/references/setup.md', notice + renderSetupMarkdown({ lang: 'en' })],
]);
for (const client of guide.clients) {
  const slug = client.id === 'claudeCode' ? 'claude-code' : client.id;
  files.set(`docs/setup/${slug}.md`, notice + renderClientMarkdown(guide, client) + `\n\n## ${guide.copy.details.verifyTitle}\n\n> ${guide.copy.details.verifyPrompt}\n\n${guide.copy.details.verifyText}\n`);
}
for (const [path, text] of files) {
  if (process.argv.includes('--check')) {
    if (readFileSync(root + path, 'utf8') !== text) throw new Error(`Stale generated guide: ${path}. Run npm run docs:generate.`);
  } else writeFileSync(root + path, text);
}
console.log(`${files.size} setup documents ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
